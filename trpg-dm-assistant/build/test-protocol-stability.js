"use strict";
const fs=require("fs"),assert=require("assert"),path=require("path");
const source=fs.readFileSync(path.join(__dirname,"../src/ai-protocol.js"),"utf8");
assert.match(source,/obj=normalizeAiProtocolShape\(obj,\{stage\}\)/);
assert.match(source,/rawCheck\.required=true/);
assert.match(source,/\[key,"by","delta"\]/);
assert.match(source,/payload=\{protocolVersion:AI_PROTOCOL_VERSION/);
const normalize=value=>String(value??"").trim().split(".").slice(0,2).map(Number).join(".");
assert.equal(normalize(1.3),"1.3");
assert.equal(normalize("1.3.0"),"1.3");
const check={type:"skill",skillId:"spot_hidden"};
const decision="check";
if(decision==="check")check.required=true;
assert.equal(check.required,true);
const change={operation:"advanceClock",by:1};
if(change.amount===undefined&&Number.isFinite(Number(change.by)))change.amount=Number(change.by);
assert.equal(change.amount,1);
console.log("Protocol stability tests passed");
